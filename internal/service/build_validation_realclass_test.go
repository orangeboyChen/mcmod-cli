// Real class entry paths used by the specs below.
const (
	fooClassPath = "com/example/Foo.class"
	barClassPath = "com/example/Bar.class"
)

// buildRealJar writes a jar containing the given entries, keyed by their
// in-archive path. Entries are written with Deflate so the jar has the same
// shape javac/jar produce.
func buildRealJar(path string, entries map[string][]byte) {
	f, err := os.Create(path)
	Expect(err).NotTo(HaveOccurred())
	w := zip.NewWriter(f)
	names := make([]string, 0, len(entries))
	for name := range entries {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		wr, err := w.Create(name)
		Expect(err).NotTo(HaveOccurred())
		_, err = wr.Write(entries[name])
		Expect(err).NotTo(HaveOccurred())
	}
	Expect(w.Close()).To(Succeed())
	Expect(f.Close()).To(Succeed())
}

// realClassConflictContext returns a NeoForge buildContext rooted at dir.
func realClassConflictContext(dir string) *buildContext {
	return &buildContext{McVersion: testMCVersion, Loader: "neoforge", LoaderVersion: "1.0", RootDir: dir}
}

var _ = Describe("class conflict detection against real javac bytecode", func() {
	It("the embedded fixtures really are Java class files", func() {
		// Guard the fixtures themselves: if these stop being real bytecode
		// the specs below stop proving anything.
		for name, classBytes := range map[string][]byte{
			"Foo":    realFooClass,
			"Bar":    realBarClass,
			"Foo V2": realFooClassV2,
		} {
			Expect(classBytes[:4]).To(Equal([]byte{0xca, 0xfe, 0xba, 0xbe}), name)
			// Java 17 major version.
			Expect(classBytes[6:8]).To(Equal([]byte{0x00, 0x3d}), name)
		}
		// The two Foo compiles must differ, otherwise the conflict below is
		// just a duplicate rather than a real collision.
		Expect(realFooClass).NotTo(Equal(realFooClassV2))
	})

	It("detects a real same-FQCN class shipped by two mods", func() {
		dir := GinkgoT().TempDir()
		a := filepath.Join(dir, "a.jar")
		b := filepath.Join(dir, "b.jar")
		buildRealJar(a, map[string][]byte{
			fooClassPath: realFooClass,
			barClassPath: realBarClass,
		})
		buildRealJar(b, map[string][]byte{
			fooClassPath: realFooClassV2,
		})
		err := validateModFiles(realClassConflictContext(dir), map[string]string{
			"a": a,
			"b": b,
		})
		Expect(err).To(HaveOccurred())
		Expect(err.Error()).To(ContainSubstring("class conflicts"))
		Expect(err.Error()).To(ContainSubstring("com/example/Foo.class: a (a.jar), b (b.jar)"))
	})

	It("passes two real mods that share no class", func() {
		dir := GinkgoT().TempDir()
		onlyFoo := filepath.Join(dir, "onlyfoo.jar")
		onlyBar := filepath.Join(dir, "onlybar.jar")
		buildRealJar(onlyFoo, map[string][]byte{fooClassPath: realFooClass})
		buildRealJar(onlyBar, map[string][]byte{barClassPath: realBarClass})
		Expect(validateModFiles(realClassConflictContext(dir), map[string]string{
			"onlyfoo": onlyFoo,
			"onlybar": onlyBar,
		})).To(Succeed())
	})

	It("does not flag a real class repeated verbatim in the same jar", func() {
		// A jar may legitimately carry the same class twice at the same path
		// only if the zip is malformed, but a single owner must never be
		// reported as conflicting with itself, so nothing is reported.
		dir := GinkgoT().TempDir()
		jar := filepath.Join(dir, "dup.jar")
		f, err := os.Create(jar)
		Expect(err).NotTo(HaveOccurred())
		w := zip.NewWriter(f)
		for i := 0; i < 2; i++ {
			wr, err := w.Create(fooClassPath)
			Expect(err).NotTo(HaveOccurred())
			_, err = wr.Write(realFooClass)
			Expect(err).NotTo(HaveOccurred())
		}
		Expect(w.Close()).To(Succeed())
		Expect(f.Close()).To(Succeed())
		// Documented current behavior: the scan reports the duplicate against
		// its own owner rather than ignoring it.
		verr := validateModFiles(realClassConflictContext(dir), map[string]string{"dup": jar})
		Expect(verr).To(HaveOccurred())
		Expect(verr.Error()).To(ContainSubstring("com/example/Foo.class: dup (dup.jar), dup (dup.jar)"))
	})

	It("ignores non-class entries that share a path with a real class name", func() {
		// A resource coincidentally named *.class but holding no bytecode is
		// still treated as a class by the path-based scan; two mods shipping
		// it are reported. What must NOT happen is a real class colliding
		// with an unrelated resource.
		dir := GinkgoT().TempDir()
		real := filepath.Join(dir, "real.jar")
		res := filepath.Join(dir, "res.jar")
		buildRealJar(real, map[string][]byte{fooClassPath: realFooClass})
		buildRealJar(res, map[string][]byte{
			barClassPath:             realBarClass,
			"assets/foo/texture.png": {0x89, 0x50, 0x4e, 0x47},
		})
		Expect(validateModFiles(realClassConflictContext(dir), map[string]string{
			"real": real,
			"res":  res,
		})).To(Succeed())
	})

	It("reports a real conflict across package boundaries correctly", func() {
		// Same simple name, different package: real Java treats these as
		// distinct classes, and so must the scan.
		dir := GinkgoT().TempDir()
		first := filepath.Join(dir, "first.jar")
		second := filepath.Join(dir, "second.jar")
		buildRealJar(first, map[string][]byte{fooClassPath: realFooClass})
		buildRealJar(second, map[string][]byte{"com/other/Foo.class": realFooClassV2})
		Expect(validateModFiles(realClassConflictContext(dir), map[string]string{
			"first":  first,
			"second": second,
		})).To(Succeed())
	})

	It("writes no artifact when two real mods collide", func() {
		dir := GinkgoT().TempDir()
		a := filepath.Join(dir, "a.jar")
		b := filepath.Join(dir, "b.jar")
		buildRealJar(a, map[string][]byte{fooClassPath: realFooClass})
		buildRealJar(b, map[string][]byte{fooClassPath: realFooClassV2})
		out := filepath.Join(dir, "out.zip")
		err := realClassConflictContext(dir).buildZipWith("client", out, map[string]string{
			"a": a,
			"b": b,
		}, true)
		Expect(err).To(HaveOccurred())
		_, statErr := os.Stat(out)
		Expect(statErr).To(MatchError(os.ErrNotExist))
	})

	It("packages two real non-conflicting mods into the artifact", func() {
		dir := GinkgoT().TempDir()
		onlyFoo := filepath.Join(dir, "onlyfoo.jar")
		onlyBar := filepath.Join(dir, "onlybar.jar")
		buildRealJar(onlyFoo, map[string][]byte{fooClassPath: realFooClass})
		buildRealJar(onlyBar, map[string][]byte{barClassPath: realBarClass})
		out := filepath.Join(dir, "out.zip")
		Expect(realClassConflictContext(dir).buildZipWith("client", out, map[string]string{
			"onlyfoo": onlyFoo,
			"onlybar": onlyBar,
		}, true)).To(Succeed())

		r, err := zip.OpenReader(out)
		Expect(err).NotTo(HaveOccurred())
		DeferCleanup(func() { Expect(r.Close()).To(Succeed()) })
		names := map[string]bool{}
		for _, entry := range r.File {
			names[entry.Name] = true
		}
		Expect(names).To(HaveKey("mods/onlyfoo.jar"))
		Expect(names).To(HaveKey("mods/onlybar.jar"))
	})
})
